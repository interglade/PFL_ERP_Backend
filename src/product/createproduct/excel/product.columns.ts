/**
 * Product column map - the single source of truth for the product export, the
 * downloadable template and the Excel importer.
 *
 * Headers match the ones the previous importer already accepted ("Product
 * Name", "Shelf Life (Days)", ...) so spreadsheets staff already have keep
 * working; the columns added here are the product fields the old importer
 * silently ignored.
 *
 * Variants are not listed one block per variant any more: the Count, Size,
 * Variety, Origin and Brand columns hold the product's allowed values as
 * comma lists, and the variants are every combination of them
 * (docs/product-variant-plan.md §7).
 */

import { ExcelColumn, ExcelSheetDefinition } from '../../../excel/excelColumn';
import { Product } from '../entity/product.entity';
import { Acceptability, QualityParameter } from '../entity/quantityParameter.entity';
import { VariantField } from '../../productAttribute/entity/productAttribute.entity';
import { sortValues } from '../../productVarient/service/variantSync';

/** The five standard attributes as sheet columns, in the order they are shown. */
export const ATTRIBUTE_COLUMNS: { header: string; code: VariantField; width: number }[] = [
  { header: 'Count', code: 'count', width: 24 },
  { header: 'Size', code: 'size', width: 24 },
  { header: 'Variety', code: 'variety', width: 28 },
  { header: 'Origin', code: 'origin', width: 24 },
  { header: 'Brand', code: 'brand', width: 20 },
];

/** "40, 50, 60" - the product's allowed values of one attribute. */
function allowedList(product: Product, code: VariantField): string | null {
  const values = sortValues(
    (product.allowedValues ?? []).filter((value) => value.attribute?.code === code),
  );
  return values.length ? values.map((value) => value.value).join(', ') : null;
}

const attributeColumns: ExcelColumn<Product>[] = ATTRIBUTE_COLUMNS.map((column) => ({
  header: column.header,
  maps: 'product_allowed_value',
  width: column.width,
  note:
    'Comma-separated list, e.g. "40, 50, 60" ("&" and "and" also separate values). ' +
    'Every combination of the values in Count, Size, Variety, Origin and Brand becomes ' +
    'one variant. Values not yet in the attribute master are added and listed in the ' +
    'import report so their spelling can be checked.',
  get: (product: Product) => allowedList(product, column.code),
}));

const variantCodesColumn: ExcelColumn<Product> = {
  header: 'Variant Codes',
  maps: 'productVarient.varient_code',
  readOnly: true,
  width: 40,
  note: 'Active variants, generated by the system.',
  get: (product: Product) =>
    (product.variant ?? [])
      .filter((variant) => variant.isActive !== false)
      .sort((a, b) => (a.sequence ?? 0) - (b.sequence ?? 0))
      .map((variant) => variant.variantCode)
      .join(', ') || null,
};

