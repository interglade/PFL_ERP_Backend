/**
 * Excel sheets for the Transporter, Driver and Vehicle registrations
 * (docs/master-data-excel-plan.md Phase 7).
 *
 * A row is turned into the same body the form sends, so the import goes through
 * each module's own `applyBody` / `assertComplete` / `assertUnique` - one set of
 * rules for the form and the sheet. The only thing done here is naming the
 * transporter: Driver and Vehicle rows name it, and the name is matched to an
 * approved or pending transporter like the form's picker offers. A name that
 * does not match leaves the link empty and makes the record a draft.
 */

import { ExcelColumn, ExcelSheetDefinition } from '../excel/excelColumn';
import { ExcelRow } from '../excel/excelImport.service';
import { DraftLinks } from '../excel/draftLinks';
import { LookupIndex } from '../excel/lookupIndex';
import { toDateOnlyString } from '../excel/excelValue';
import { Status } from '../utils/status.enum';
import { TransporterType } from '../transporter/entity/transporter.entity';

/** The Transporter a Driver or Vehicle row can name. */
export interface TransporterRef {
  id: string;
  name: string | null;
  transporterCode: string | null;
  status: Status;
}

export interface TransportRowContext {
  /** Transporters the form's picker offers: approved and pending. */
  pickable: LookupIndex<TransporterRef>;
  /** Drafts and rejected ones, only to explain why a name was not linked. */
  unavailable: LookupIndex<TransporterRef>;
  draft: DraftLinks;
}

/** A form body built from a row, and the name to show for it in the report. */
export interface TransportRowBody {
  body: Record<string, unknown>;
  name: string | null;
}

/** Splits transporters into the ones a row may link and the ones it may not. */
export function transporterIndexes(transporters: TransporterRef[]) {
  const options = { names: (t: TransporterRef) => [t.name, t.transporterCode] };
  const pickable = (t: TransporterRef) => t.status === Status.APPROVED || t.status === Status.PENDING;
  return {
    pickable: LookupIndex.fromRecords(transporters.filter(pickable), options),
    unavailable: LookupIndex.fromRecords(transporters.filter((t) => !pickable(t)), options),
  };
}

// ── Shared columns ───────────────────────────────────────────────────────────

const ADDRESS_COLUMNS: { header: string; property: string }[] = [
  { header: 'Address 1', property: 'address1' },
  { header: 'Address 2', property: 'address2' },
  { header: 'Location / Area', property: 'location' },
  { header: 'City', property: 'city' },
  { header: 'State', property: 'state' },
  { header: 'Pincode', property: 'pincode' },
];

const addressColumns = <T extends { address?: any }>(table: string): ExcelColumn<T>[] =>
  ADDRESS_COLUMNS.map(({ header, property }) => ({
    header,
    maps: `addresses.${property} (${table}.address)`,
    width: property === 'address1' ? 30 : 18,
    get: (record: T) => record.address?.[property],
  }));

const codeColumn = <T>(header: string, maps: string, get: (record: T) => unknown, label: string): ExcelColumn<T> => ({
  header,
  maps,
  key: true,
  width: 14,
  note:
    `Generated by the system - leave it empty for a new ${label}. Keep it on a row ` +
    `exported from a draft ${label}: importing the row again fills in the cells ` +
    'that have a value and, once nothing is missing, sends it for approval',
  get,
});

const statusColumn = <T extends { status?: Status }>(maps: string): ExcelColumn<T> => ({
  header: 'Status',
  maps,
  readOnly: true,
  width: 12,
  get: (record) => record.status,
});

const transporterColumn = <T extends { transporter?: any }>(maps: string): ExcelColumn<T> => ({
  header: 'Transporter',
  maps,
  width: 28,
  listFrom: 'transporter',
  link: { master: 'Transporter' },
  note:
    'Name or code of an approved or pending transporter. Leave empty for an ' +
    'independent / own one. If it does not match, it is left empty and the record is saved as draft',
  get: (record) => record.transporter?.name,
});

/** Trimmed text of a cell, or undefined when blank so the body leaves the field alone. */
const cell = (row: ExcelRow, header: string): string | undefined => row.text(header) ?? undefined;

/** Puts only the filled cells into the body: a blank cell never clears a value. */
function fill(body: Record<string, unknown>, row: ExcelRow, map: Record<string, string>): void {
  for (const [property, header] of Object.entries(map)) {
    const value = cell(row, header);
    if (value !== undefined) body[property] = value;
  }
}

function addressFromRow(row: ExcelRow): Record<string, string> | undefined {
  const address: Record<string, string> = {};
  for (const { header, property } of ADDRESS_COLUMNS) {
    const value = cell(row, header);
    if (value !== undefined) address[property] = value;
  }
  return Object.keys(address).length ? address : undefined;
}

/** Matches the Transporter cell; blank means independent. */
function linkTransporter(row: ExcelRow, body: Record<string, unknown>, context: TransportRowContext): void {
  const typed = cell(row, 'Transporter');
  if (!typed) return;

  const found = context.pickable.match(typed);
  if (found) {
    body.transporterId = found.id;
    return;
  }

  const blocked = context.unavailable.match(typed);
  if (blocked) {
    context.draft.note(
      'Transporter',
      typed,
      `"${blocked.name}" is ${blocked.status} - it can be linked once it is ${Status.APPROVED} or ${Status.PENDING}`,
    );
    return;
  }
  context.draft.one(context.pickable, 'Transporter', typed);
}

// ── Transporter ──────────────────────────────────────────────────────────────

export const TRANSPORTER_TYPE_LABELS: Record<TransporterType, string> = {
  [TransporterType.FLEET_OWNER]: 'Fleet Owner',
  [TransporterType.BROKER]: 'Broker',
  [TransporterType.OWN_FLEET]: 'Own Fleet',
};

/** "Fleet Owner" or "fleet-owner" -> `fleet-owner`; anything else is passed on for the form's check to reject. */
function transporterTypeValue(text: string): string {
  const key = text.toLowerCase().replace(/[\s_-]+/g, '');
  const match = (Object.entries(TRANSPORTER_TYPE_LABELS) as [string, string][]).find(
    ([value, label]) =>
      value.replace(/-/g, '') === key || label.toLowerCase().replace(/\s+/g, '') === key,
  );
  return match ? match[0] : text;
}

