export function transporterRowBody(row: ExcelRow): TransportRowBody {
  const body: Record<string, unknown> = {};
  fill(body, row, {
    name: 'Name',
    contactPerson: 'Contact Person',
    primaryPhone: 'Primary Phone',
    altPhone: 'Alternate Phone',
    email: 'Email',
    gstin: 'GSTIN',
    pan: 'PAN',
    bankName: 'Bank Name',
    accountHolderName: 'Account Holder Name',
    accountNo: 'Account No',
    ifsc: 'IFSC',
    upiId: 'UPI ID',
    paymentTerms: 'Payment Terms',
    creditDays: 'Credit Days',
    remarks: 'Remarks',
  });
  const type = cell(row, 'Transporter Type');
  if (type) body.transporterType = transporterTypeValue(type);
  const address = addressFromRow(row);
  if (address) body.address = address;
  return { body, name: (body.name as string) ?? null };
}

