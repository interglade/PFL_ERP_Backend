export const LICENCE_TYPES = ['LMV', 'LMV-TR', 'HMV', 'HGMV', 'HPMV'];

export const DRIVER_SHEET: ExcelSheetDefinition<any> = {
  sheetName: 'Drivers',
  columns: [
    codeColumn('Driver Code', 'drivers.driverCode', (d: any) => d.driverCode, 'driver'),
    { header: 'First Name', maps: 'drivers.firstName', required: true, width: 18, get: (d) => d.firstName },
    { header: 'Last Name', maps: 'drivers.lastName', width: 18, get: (d) => d.lastName },
    {
      header: 'Phone Number',
      maps: 'drivers.phoneNumber',
      required: true,
      width: 16,
      note: '10-digit mobile number. Unique - a phone already registered skips the row',
      get: (d) => d.phoneNumber,
    },
    { header: 'Alternate Phone', maps: 'drivers.altPhoneNumber', width: 16, get: (d) => d.altPhoneNumber },
    { header: 'Email', maps: 'drivers.email', width: 26, note: 'Unique', get: (d) => d.email },
    { header: 'Licence No', maps: 'drivers.licenseNo', width: 20, note: 'Unique', get: (d) => d.licenseNo },
    {
      header: 'Licence Type',
      maps: 'drivers.licenseType',
      enumValues: LICENCE_TYPES,
      width: 14,
      get: (d) => d.licenseType,
    },
    {
      header: 'Licence Expiry',
      maps: 'drivers.licenseExpiry',
      type: 'date',
      width: 14,
      get: (d) => d.licenseExpiry,
    },
    transporterColumn('drivers.transporter_id -> transporters.name'),
    ...addressColumns<any>('drivers'),
    { header: 'Remarks', maps: 'drivers.remarks', width: 30, get: (d) => d.remarks },
    statusColumn('drivers.status'),
  ],
};

const LICENCE_EXPIRY = DRIVER_SHEET.columns.find((column) => column.header === 'Licence Expiry')!;

export function driverRowBody(row: ExcelRow, context: TransportRowContext): TransportRowBody {
  const body: Record<string, unknown> = {};
  fill(body, row, {
    firstName: 'First Name',
    lastName: 'Last Name',
    phoneNumber: 'Phone Number',
    altPhoneNumber: 'Alternate Phone',
    email: 'Email',
    licenseNo: 'Licence No',
    licenseType: 'Licence Type',
    remarks: 'Remarks',
  });

  // A real date cell or typed text: both become YYYY-MM-DD; anything else is
  // passed on as typed so the form's own check reports it.
  const expiry = row.raw(LICENCE_EXPIRY.header);
  if (expiry !== null && expiry !== undefined && expiry !== '') {
    body.licenseExpiry = toDateOnlyString(expiry) ?? String(expiry);
  }

  const address = addressFromRow(row);
  if (address) body.address = address;
  linkTransporter(row, body, context);

  const name = [body.firstName, body.lastName].filter(Boolean).join(' ');
  return { body, name: name || null };
}

