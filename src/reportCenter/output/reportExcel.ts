import ExcelJS from 'exceljs';
import moment from 'moment-timezone';
import { changePct } from '../engine/format';
import { ColumnType, ReportColumn, ReportResult, TableRow } from '../reportCenter.types';

/** Indian grouping (12,34,567.00) in an Excel number format. */
const INDIAN_2 = '[>=10000000]##\\,##\\,##\\,##0.00;[>=100000]##\\,##\\,##0.00;##,##0.00';
const INDIAN_0 = '[>=10000000]##\\,##\\,##\\,##0;[>=100000]##\\,##\\,##0;##,##0';

const NUM_FMT: Partial<Record<ColumnType, string>> = {
  inr: INDIAN_2,
  rate: INDIAN_2,
  kg: INDIAN_2,
  qty: INDIAN_2,
  pct: '0.0"%"',
  count: INDIAN_0,
  days: '0',
  date: 'dd-mmm-yyyy',
};

const HEAD_FILL: ExcelJS.Fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF1F4E78' } };
const fill = (argb: string): ExcelJS.Fill => ({ type: 'pattern', pattern: 'solid', fgColor: { argb } });
const ROW_FILL: Partial<Record<TableRow['kind'], ExcelJS.Fill>> = {
  group: fill('FFE8EEF5'),
  subtotal: fill('FFF6F8FA'),
  total: fill('FFDDE6EF'),
  opening: fill('FFF3F6F9'),
  closing: fill('FFF3F6F9'),
};

/** "03 Nov 2026" text from the engine -> a real Excel date. */
function cellValue(v: unknown, type: ColumnType): ExcelJS.CellValue {
  if (v === null || v === undefined || v === '') return null;
  if (type === 'date') {
    const m = moment.utc(String(v), ['DD MMM YYYY', 'YYYY-MM-DD'], true);
    return m.isValid() ? m.toDate() : String(v);
  }
  if (type === 'text') return String(v);
  const n = Number(v);
  return Number.isFinite(n) ? n : String(v);
}

function headerBlock(ws: ExcelJS.Worksheet, r: ReportResult, width: number) {
  const lines: [string, Partial<ExcelJS.Font>][] = [
    [r.company?.name ?? 'Prime Fresh', { bold: true, size: 14, color: { argb: 'FF1F4E78' } }],
    [`${r.title} (${r.code})`, { bold: true, size: 12 }],
    ...r.paramsSummary.map((p): [string, Partial<ExcelJS.Font>] => [`${p.label}: ${p.value}`, { size: 10, color: { argb: 'FF5B6470' } }]),
    [`Generated by ${r.generatedBy} on ${r.generatedAt}`, { italic: true, size: 9, color: { argb: 'FF8A939E' } }],
  ];
  if (r.party) {
    lines.splice(2, 0, [`${r.party.title}: ${r.party.name}`, { bold: true, size: 11 }], ...r.party.lines.map((l): [string, Partial<ExcelJS.Font>] => [l, { size: 10 }]));
  }
  for (const [text, font] of lines) {
    const row = ws.addRow([text]);
    row.font = font;
    ws.mergeCells(row.number, 1, row.number, Math.max(width, 1));
  }
  ws.addRow([]);
}

function writeHeader(ws: ExcelJS.Worksheet, cols: ReportColumn[]) {
  const head = ws.addRow(cols.map((c) => c.label));
  head.eachCell((cell) => {
    cell.fill = HEAD_FILL;
    cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    cell.alignment = { vertical: 'bottom', wrapText: true };
  });
  head.height = 30;
  return head.number;
}

function setWidths(ws: ExcelJS.Worksheet, cols: ReportColumn[]) {
  cols.forEach((c, i) => {
    const col = ws.getColumn(i + 1);
    col.width = Math.max(c.width ?? 12, Math.min(c.label.length + 2, 24));
    const fmt = NUM_FMT[c.type];
    if (fmt) col.numFmt = fmt;
  });
}

/**
 * Report sheet: header block, frozen column headings with filters, group headings, detail rows,
 * subtotals and grand total. Excel outline levels let the user collapse to group totals with
 * the 1 / 2 / 3 buttons. Summary sheet: the KPIs. Data sheet: flat detail rows for pivots.
 */
export async function reportWorkbook(r: ReportResult, detailRows: Record<string, any>[], groupCount: number): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = r.generatedBy;
  wb.created = new Date();
  const cols = r.columns;

  // ── Report ──
  const ws = wb.addWorksheet('Report', {
    properties: { outlineLevelRow: groupCount, outlineProperties: { summaryBelow: true, summaryRight: false } } as any,
    pageSetup: { orientation: r.layout.orientation, paperSize: 9, fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });
  setWidths(ws, cols);
  headerBlock(ws, r, cols.length);
  const headRow = writeHeader(ws, cols);
  ws.views = [{ state: 'frozen', ySplit: headRow }];
  ws.autoFilter = { from: { row: headRow, column: 1 }, to: { row: headRow, column: cols.length } };

  for (const t of r.rows) {
    const values = cols.map((c, i) => {
      if (i === 0 && t.kind !== 'detail') return t.label ?? '';
      return t.kind === 'group' ? null : cellValue(t.cells[c.key], c.type);
    });
    const row = ws.addRow(values);
    if (t.kind === 'detail') {
      row.outlineLevel = groupCount;
    } else {
      row.font = { bold: true };
      if (ROW_FILL[t.kind]) row.eachCell({ includeEmpty: true }, (cell) => (cell.fill = ROW_FILL[t.kind]!));
      if (t.kind === 'group' || t.kind === 'subtotal') row.outlineLevel = t.level;
      if (t.kind === 'group') ws.mergeCells(row.number, 1, row.number, cols.length);
    }
    if (t.kind !== 'detail' && t.kind !== 'group') row.getCell(1).alignment = { indent: t.level };
  }
  if (!r.rows.length) ws.addRow(['No records for these filters']);
  if (r.truncated) ws.addRow(['Too many rows to show in full. The Data sheet has every row.']).font = { italic: true, color: { argb: 'FFC0392B' } };

  // ── Summary ──
  const ss = wb.addWorksheet('Summary');
  ss.columns = [{ width: 32 }, { width: 18 }, { width: 18 }, { width: 12 }];
  headerBlock(ss, r, 4);
  const sh = ss.addRow(['Measure', 'Value', 'Previous period', 'Change %']);
  sh.eachCell((c) => {
    c.fill = HEAD_FILL;
    c.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  });
  for (const k of r.kpis) {
    const ch = changePct(k.value, k.previous);
    const row = ss.addRow([k.label, k.value, k.previous ?? null, ch === null ? null : ch]);
    const fmt = NUM_FMT[k.type] ?? INDIAN_2;
    row.getCell(2).numFmt = fmt;
    row.getCell(3).numFmt = fmt;
    row.getCell(4).numFmt = '0.0"%"';
  }
  if (r.notes.length) {
    ss.addRow([]);
    for (const n of r.notes) ss.addRow([n]).font = { italic: true, size: 9, color: { argb: 'FF5B6470' } };
  }

  // ── Data ──
  const ds = wb.addWorksheet('Data');
  setWidths(ds, cols);
  writeHeader(ds, cols);
  ds.views = [{ state: 'frozen', ySplit: 1 }];
  ds.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: cols.length } };
  for (const d of detailRows) ds.addRow(cols.map((c) => cellValue(d[c.key], c.type)));

  return Buffer.from(await wb.xlsx.writeBuffer());
}

/** Flat detail rows as CSV (UTF-8 with BOM so Excel opens it correctly). */
export function reportCsv(cols: ReportColumn[], detailRows: Record<string, any>[]): Buffer {
  const esc = (v: unknown) => {
    const s = v === null || v === undefined ? '' : String(v);
    return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const lines = [cols.map((c) => esc(c.label)).join(','), ...detailRows.map((d) => cols.map((c) => esc(d[c.key])).join(','))];
  return Buffer.from('﻿' + lines.join('\r\n'), 'utf8');
}
